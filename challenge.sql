                v_mensagem_erro
            );
            dbms_output.put_line(v_mensagem_erro);
         WHEN NO_DATA_FOUND THEN
            v_codigo_erro := TO_CHAR(SQLCODE);
            v_mensagem_erro := SUBSTR(SQLERRM, 1, 400);
