                INSERT INTO LOGS(
                    nm_procedure,
                    nm_usuario,
                    dt_ocorrencia,
                    codigo_erro,
                    mensagem_erro 
                )VALUES (
                    'dados_vet_clinica',
                    USER,
                    SYSDATE,
                    v_codigo_erro, 
                    v_mensagem_erro
                );
                dbms_output.put_line('Id vet não encontrado');
            ELSIF v_id_clinica = 0 THEN
               INSERT INTO LOGS(
                    nm_procedure,
                    nm_usuario,
                    dt_ocorrencia,
                    codigo_erro,
                    mensagem_erro 
                )VALUES (
                    'dados_vet_clinica',
                    USER,
                    SYSDATE,
                    v_codigo_erro, 
                    v_mensagem_erro
                );
                dbms_output.put_line('Id clinica não encontrado');
            ELSE
                INSERT INTO LOGS(
                    nm_procedure,
                    nm_usuario,
                    dt_ocorrencia,
                    codigo_erro,
                    mensagem_erro 
                )VALUES (
                    'dados_vet_clinica',
                    USER,
                    SYSDATE,
                    v_codigo_erro, 
                    v_mensagem_erro
                );
                dbms_output.put_line('Id clinica e vet não encontrado');
            END IF;
        WHEN OTHERS THEN
            v_codigo_erro := TO_CHAR(SQLCODE);
            v_mensagem_erro := SUBSTR(SQLERRM, 1, 400);
