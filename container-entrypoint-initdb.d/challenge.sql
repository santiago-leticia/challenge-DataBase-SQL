        OPEN c_animais;
        FETCH c_animais BULK COLLECT INTO v_animais;
        CLOSE c_animais;

        FOR i IN 1..v_animais.COUNT LOOP
            v_totalAnimais := v_totalAnimais + v_animais(i).qtd_animais;
