    CURSOR c_animais IS
        SELECT
            especie_animal,
            COUNT(id_animal)            AS qtd_animais,
            ROUND(AVG(peso_animal), 2)  AS peso_medio,
            MAX(peso_animal)            AS maior_peso,
            MIN(peso_animal)            AS menor_peso
        FROM T_CLYVO_ANIMAL
        GROUP BY especie_animal
        ORDER BY especie_animal;

    TYPE t_animais IS TABLE OF c_animais%ROWTYPE;
    v_animais t_animais;

BEGIN
